function diff(a: string | null, b: string): DiffLine[] {
  const x = (a ?? "")
    .replace(/\n$/, "")
    .split("\n")
    .filter((line, _i, arr) => a !== null || arr.length > 1 || line !== "");
  const y = b.replace(/\n$/, "").split("\n");
  const out: DiffLine[] = [];
  let i = 0;
  let j = 0;
  while (i < x.length || j < y.length) {
    if (i < x.length && j < y.length && x[i] === y[j]) {
      out.push({ kind: "ctx", text: x[i] });
      i++;
      j++;
    } else if (i < x.length && !y.slice(j).includes(x[i])) out.push({ kind: "del", text: x[i++] });
    else out.push({ kind: "add", text: y[j++] });
  }
  return out;
}

function plan(draft: AppState): SavePlan {
  const before = new Map(files(state).map((f) => [f.path, f.content]));
  const pending = files(draft).map((f) => {
    const cur = before.get(f.path) ?? null;
    return {
      path: f.path,
      displayPath: f.display,
      kind: "GitConfig" as const,
      content: f.content,
      currentContent: cur,
      drifted: false,
      hasChanges: cur !== f.content,
      diff: diff(cur, f.content),
    };
  });
  const after = new Set(pending.map((f) => f.path));
  const del = [...before.entries()]
    .filter(([p]) => !after.has(p))
    .map(([path, c]) => ({
      path,
      displayPath: path.replace(HOME, "~").replace(/\\/g, "/"),
      currentContent: c,
    }));
  const errors: string[] = [];
  if (
    draft.Profiles.length &&
    draft.Profiles.filter((p) => p.IsDefault).length !== 1 &&
    draft.Settings.NoProfileMode === "DefaultProfile"
  )
    errors.push("Debe haber exactamente un perfil por defecto.");
  return {
    files: pending,
    filesToDelete: del,
    errors,
    canSave: !errors.length,
    hasDrift: false,
    hasChanges: pending.some((f) => f.hasChanges) || del.length > 0,
  };
}

function conflicts(s: AppState) {
  const rows = orderedRules(s).filter((r) => r.rule.Type === "Folder");
  const out = [];
  for (let i = 0; i < rows.length; i++)
    for (let j = i + 1; j < rows.length; j++) {
      const [a, b] = [rows[i], rows[j]];
      if (a.profile.Id === b.profile.Id || a.profile.GitUserEmail === b.profile.GitUserEmail) continue;
      const [x, y] = [a.rule.Value.toLowerCase(), b.rule.Value.toLowerCase()];
      if (x.startsWith(y) || y.startsWith(x))
        out.push({
          severity: "Warning" as const,
          message: i18n.language.startsWith("en")
            ? `Nested folders: ${a.rule.Value} (“${a.profile.DisplayName}”) and ${b.rule.Value} (“${b.profile.DisplayName}”). “${b.profile.DisplayName}” wins in the shared part.`
            : `Carpetas anidadas: ${a.rule.Value} («${a.profile.DisplayName}») y ${b.rule.Value} («${b.profile.DisplayName}»). En la parte común gana «${b.profile.DisplayName}».`,
          ruleA: a.rule.Id,
          ruleB: b.rule.Id,
        });
    }
  return out;
}

