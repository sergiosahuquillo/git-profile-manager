function profileFile(p: Profile): string {
  const l = [
    "# Generated by GitProfile Manager. Do not edit by hand.",
    `# Profile: ${p.DisplayName}`,
    "[user]",
    `\tname = ${p.GitUserName}`,
    `\temail = ${p.GitUserEmail}`,
  ];
  if (p.Signing !== "None" && p.SigningKey) l.push(`\tsigningkey = ${p.SigningKey}`);
  if (p.SshKeyPath) l.push("[core]", `\tsshCommand = ${SSH} -i ${p.SshKeyPath} -o IdentitiesOnly=yes`);
  else if (!p.IsDefault) l.push("[core]", `\tsshCommand = ${SSH}`);
  if (p.HttpsUsername) l.push(`[credential "https://${p.Host}"]`, `\tusername = ${p.HttpsUsername}`);
  if (p.Signing === "Ssh" && p.SigningKey)
    l.push(
      "[gpg]",
      "\tformat = ssh",
      '[gpg "ssh"]',
      `\tprogram = ${KEYGEN}`,
      "\tallowedSignersFile = ~/.gitprofiles/allowed_signers",
      "[commit]",
      "\tgpgsign = true",
    );
  else if (!p.IsDefault) l.push("[gpg]", "\tformat = openpgp", "[commit]", "\tgpgsign = false");
  return `${l.join("\n")}\n`;
}

function rulesFile(s: AppState): string {
  const l = ["# Generated by GitProfile Manager. Do not edit by hand."];
  const def = s.Profiles.find((p) => p.IsDefault);
  if (s.Settings.NoProfileMode === "Strict")
    l.push("# Strict mode: a repo with no matching rule can't commit.", "[user]", "\tuseConfigOnly = true");
  else if (def)
    l.push(
      "# Default profile: applies to every repo without a rule.",
      "[include]",
      `\tpath = ${def.Slug}.gitconfig`,
    );
  const ordered = orderedRules(s);
  if (ordered.length) l.push("", "# Rules: evaluated afterwards, they override the default profile.");
  for (const { profile: p, rule: r } of ordered)
    for (const c of conditionsFor(p, r)) l.push(`[includeIf "${c}"]`, `\tpath = ${p.Slug}.gitconfig`);
  return `${l.join("\n")}\n`;
}

