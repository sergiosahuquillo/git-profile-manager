//! Genera `rules.gitconfig`, `<slug>.gitconfig`, `gitprofile.conf` y `allowed_signers`
//! a partir de `profiles.json`. Funciones puras: no escribe en disco.

use std::path::Path;

use serde::Serialize;
use ts_rs::TS;

use crate::app_paths::AppPaths;
use crate::config::gitconfig_doc::GitConfigDocument;
use crate::git::url::encode_spaces;
use crate::models::{
    AZURE_HOST, AZURE_LEGACY_SSH_HOST, AZURE_SSH_HOST, AppState, GitProvider, NoProfileMode, Profile, Rule, RuleType,
    SigningMode, SshClientKind, blank, is_azure_host, ssh_host,
};

pub const HEADER: &str = "Generated by GitProfile Manager. Do not edit by hand.";

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, TS)]
#[ts(export)]
pub enum GeneratedFileKind {
    GitConfig,
    Text,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedFile {
    pub path: String,
    pub content: String,
    pub kind: GeneratedFileKind,
}

/// Rutas del cliente SSH elegido, con barras `/` para usarlas en la configuración de Git.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export)]
pub struct SshClientInfo {
    pub kind: SshClientKind,
    pub ssh_path: String,
    pub ssh_keygen_path: String,
    /// Prefijo de `core.sshCommand` (vacío o con espacio final). Con OpenSSH de Windows fija el agente de
    /// Windows: quien lance Git (p. ej. SourceTree con su propio ssh-agent) puede haber puesto otro
    /// `SSH_AUTH_SOCK`, y entonces `ssh.exe` no vería las claves cargadas y pediría la passphrase.
    pub ssh_command_prefix: String,
}

/// Tubería del servicio ssh-agent de Windows.
pub const WINDOWS_AGENT_PIPE: &str = r"\\.\pipe\openssh-ssh-agent";

impl SshClientInfo {
    pub fn windows_openssh() -> Self {
        SshClientInfo {
            kind: SshClientKind::WindowsOpenSsh,
            ssh_path: "C:/Windows/System32/OpenSSH/ssh.exe".into(),
            ssh_keygen_path: "C:/Windows/System32/OpenSSH/ssh-keygen.exe".into(),
            ssh_command_prefix: format!("SSH_AUTH_SOCK='{WINDOWS_AGENT_PIPE}' "),
        }
    }

    pub fn resolve(kind: SshClientKind, git_install_root: Option<&Path>) -> Self {
        if let (SshClientKind::GitBundled, Some(root)) = (kind, git_install_root) {
            let root = root.to_string_lossy().replace('\\', "/");
            let root = root.trim_end_matches('/');
            return SshClientInfo {
                kind,
                ssh_path: format!("{root}/usr/bin/ssh.exe"),
                ssh_keygen_path: format!("{root}/usr/bin/ssh-keygen.exe"),
                // El SSH de Git usa el agente de su sesión (el de Git Bash o el de SourceTree): no se toca.
                ssh_command_prefix: String::new(),
            };
        }
        Self::windows_openssh()
    }

    pub fn native_ssh_path(&self) -> String {
        self.ssh_path.replace('/', "\\")
    }

    pub fn native_ssh_keygen_path(&self) -> String {
        self.ssh_keygen_path.replace('/', "\\")
    }

    /// `ssh-add.exe` junto a `ssh.exe`.
    pub fn native_ssh_add_path(&self) -> String {
        let ssh = self.native_ssh_path();
        Path::new(&ssh).parent().map(|d| d.join("ssh-add.exe").to_string_lossy().into_owned()).unwrap_or_default()
    }
}

pub struct ConfigGenerator<'a> {
    pub paths: &'a AppPaths,
}

/// Reglas en orden de aplicación: carpetas primero, remotos después (el remoto prevalece).
pub fn ordered_rules(state: &AppState) -> Vec<(&Profile, &Rule)> {
    let mut v: Vec<(&Profile, &Rule)> = state.profiles.iter().flat_map(|p| p.rules.iter().map(move |r| (p, r))).collect();
    // Orden estable, como OrderBy().ThenBy() de LINQ.
    v.sort_by_key(|(_, r)| (if r.kind == RuleType::Folder { 0 } else { 1 }, r.order));
    v
}

/// Condiciones `includeIf` que genera una regla.
pub fn conditions(profile: &Profile, rule: &Rule) -> Vec<String> {
    if rule.kind == RuleType::Folder {
        let folder = normalize_folder(&rule.value);
        return if folder.is_empty() { vec![] } else { vec![format!("gitdir/i:{folder}")] };
    }
    let host = if blank(&rule.host) { profile.host.clone() } else { rule.host.as_deref().unwrap_or("").trim().to_string() };
    let org = normalize_org(&rule.value);
    if host.is_empty() || org.is_empty() {
        return vec![];
    }
    if is_azure_host(&host) || (blank(&rule.host) && profile.provider == GitProvider::AzureDevOps) {
        return azure_conditions(&org);
    }
    vec![
        format!("hasconfig:remote.*.url:git@{host}:{org}/**"),
        format!("hasconfig:remote.*.url:https://{host}/{org}/**"),
    ]
}

/// Azure DevOps: `org` u `org/proyecto`. `hasconfig` compara la URL literal, así que se generan todas las
/// formas con las que suele aparecer: SSH, HTTPS con y sin `org@` (la que copia Azure lo lleva) y las
/// heredadas de `visualstudio.com`.
fn azure_conditions(org_path: &str) -> Vec<String> {
    let org_path = encode_spaces(org_path);
    let (org, project) = match org_path.split_once('/') {
        Some((o, p)) => (o.to_string(), Some(p.to_string())),
        None => (org_path.clone(), None),
    };
    let legacy_https = match &project {
        Some(p) => format!("https://{org}.visualstudio.com/{p}/**"),
        None => format!("https://{org}.visualstudio.com/**"),
    };
    [
        format!("git@{AZURE_SSH_HOST}:v3/{org_path}/**"),
        format!("https://{AZURE_HOST}/{org_path}/**"),
        format!("https://{org}@{AZURE_HOST}/{org_path}/**"),
        format!("{org}@{AZURE_LEGACY_SSH_HOST}:v3/{org_path}/**"),
        legacy_https,
    ]
    .into_iter()
    .map(|u| format!("{HASCONFIG_URL}{u}"))
    .collect()
}

pub const HASCONFIG_URL: &str = "hasconfig:remote.*.url:";

/// Barras `/` y barra final (la barra final hace la regla recursiva).
pub fn normalize_folder(folder: &str) -> String {
    let mut f = folder.trim().trim_matches('"').replace('\\', "/");
    if f.is_empty() {
        return f;
    }
    while f.contains("//") {
        f = f.replace("//", "/");
    }
    if f.ends_with('/') { f } else { f + "/" }
}

pub fn normalize_org(org: &str) -> String {
    org.trim().trim_matches('/').replace('\\', "/")
}

/// `core.sshCommand` del perfil. Git lo ejecuta con `sh`, así que admite asignar variables delante.
pub fn build_ssh_command(ssh: &SshClientInfo, key_path: &str) -> String {
    format!("{}{} -i {} -o IdentitiesOnly=yes", ssh.ssh_command_prefix, shell_quote(&ssh.ssh_path), shell_quote(key_path))
}

/// `core.sshCommand` sin clave fija (perfiles que anulan la del perfil por defecto).
pub fn bare_ssh_command(ssh: &SshClientInfo) -> String {
    format!("{}{}", ssh.ssh_command_prefix, shell_quote(&ssh.ssh_path))
}

/// `gpg.ssh.program`. Git lo ejecuta sin shell, así que con OpenSSH de Windows se usa un envoltorio
/// (`~/.gitprofiles/ssh-keygen.cmd`) que fija el agente de Windows antes de llamar a `ssh-keygen`.
pub fn signing_program(paths: &AppPaths, ssh: &SshClientInfo) -> String {
    if ssh.kind == SshClientKind::WindowsOpenSsh { paths.signing_wrapper_file().replace('\\', "/") } else { ssh.ssh_keygen_path.clone() }
}

/// Contenido de `ssh-keygen.cmd` (CRLF, como espera `cmd.exe`).
pub fn signing_wrapper(ssh: &SshClientInfo) -> String {
    [
        "@echo off".to_string(),
        format!("rem {HEADER}"),
        "rem Signs with the Windows ssh-keygen, always through the Windows agent, even if whatever launches Git".into(),
        "rem (e.g. SourceTree with its own ssh-agent) has set another SSH_AUTH_SOCK.".into(),
        format!("set \"SSH_AUTH_SOCK={WINDOWS_AGENT_PIPE}\""),
        format!("\"{}\" %*", ssh.native_ssh_keygen_path()),
        String::new(),
    ]
    .join("\r\n")
}

fn shell_quote(s: &str) -> String {
    if s.contains(' ') { format!("\"{s}\"") } else { s.to_string() }
}

pub fn ssh_alias(p: &Profile) -> String {
    if crate::models::is_azure(p) {
        return format!("azure-{}", p.slug);
    }
    let first = p.host.split('.').next().unwrap_or("");
    let prefix = if first.is_empty() { "git" } else { first };
    format!("{prefix}-{}", p.slug)
}

impl<'a> ConfigGenerator<'a> {
    pub fn new(paths: &'a AppPaths) -> Self {
        ConfigGenerator { paths }
    }

    pub fn generate_all(&self, state: &AppState, ssh: &SshClientInfo) -> Vec<GeneratedFile> {
        let mut files = vec![GeneratedFile {
            path: self.paths.rules_file(),
            content: self.generate_rules(state),
            kind: GeneratedFileKind::GitConfig,
        }];
        for p in &state.profiles {
            files.push(GeneratedFile {
                path: self.paths.profile_file(&p.slug),
                content: self.generate_profile(p, ssh),
                kind: GeneratedFileKind::GitConfig,
            });
        }
        if ssh.kind == SshClientKind::WindowsOpenSsh {
            files.push(GeneratedFile {
                path: self.paths.signing_wrapper_file(),
                content: signing_wrapper(ssh),
                kind: GeneratedFileKind::Text,
            });
        }
        files.push(GeneratedFile {
            path: self.paths.allowed_signers_file(),
            content: self.generate_allowed_signers(state),
            kind: GeneratedFileKind::Text,
        });
        if state.settings.generate_ssh_aliases {
            files.push(GeneratedFile {
                path: self.paths.ssh_aliases_file(),
                content: self.generate_ssh_aliases(state),
                kind: GeneratedFileKind::Text,
            });
        }
        files
    }

    pub fn generate_rules(&self, state: &AppState) -> String {
        let mut doc = GitConfigDocument::new();
        doc.comment(HEADER);
        if state.settings.no_profile_mode == NoProfileMode::Strict {
            doc.comment("Strict mode: a repo with no matching rule can't commit.")
                .section("user", None)
                .set("useConfigOnly", "true");
        } else if let Some(def) = state.default_profile() {
            doc.comment("Default profile: applies to every repo without a rule.")
                .section("include", None)
                .set("path", &format!("{}.gitconfig", def.slug));
        }

        let ordered = ordered_rules(state);
        if !ordered.is_empty() {
            doc.blank_line().comment("Rules: evaluated afterwards, they override the default profile.");
        }
        for (profile, rule) in ordered {
            for condition in conditions(profile, rule) {
                doc.section("includeIf", Some(&condition)).set("path", &format!("{}.gitconfig", profile.slug));
            }
        }
        doc.finish()
    }

    pub fn generate_profile(&self, p: &Profile, ssh: &SshClientInfo) -> String {
        let mut doc = GitConfigDocument::new();
        doc.comment(HEADER)
            .comment(&format!("Profile: {}", p.display_name))
            .section("user", None)
            .set("name", &p.git_user_name)
            .set("email", &p.git_user_email);

        let has_signing_key = !blank(&p.signing_key);
        let signing_key = p.signing_key.as_deref().unwrap_or("");
        if p.signing != SigningMode::None && has_signing_key {
            doc.set("signingkey", signing_key);
        }

        // Un perfil aplicado por regla se evalúa encima del perfil por defecto (y de reglas anteriores):
        // lo que no defina lo heredaría de ellos. Por eso anula explícitamente la clave SSH y la firma.
        // El perfil por defecto no anula nada para no pisar la configuración global del usuario.
        let reset_inherited = !p.is_default;

        if !blank(&p.ssh_key_path) {
            doc.section("core", None).set("sshCommand", &build_ssh_command(ssh, p.ssh_key_path.as_deref().unwrap()));
        } else if reset_inherited {
            doc.section("core", None).set("sshCommand", &bare_ssh_command(ssh));
        }

        if !blank(&p.https_username) && !p.host.trim().is_empty() {
            doc.section("credential", Some(&format!("https://{}", p.host)))
                .set("username", p.https_username.as_deref().unwrap());
        }

        if p.signing == SigningMode::Ssh && has_signing_key {
            doc.section("gpg", None)
                .set("format", "ssh")
                .section("gpg", Some("ssh"))
                .set("program", &signing_program(self.paths, ssh))
                .set("allowedSignersFile", "~/.gitprofiles/allowed_signers")
                .section("commit", None)
                .set("gpgsign", "true");
        } else if p.signing == SigningMode::Gpg && has_signing_key {
            doc.section("gpg", None).set("format", "openpgp").section("commit", None).set("gpgsign", "true");
        } else if reset_inherited {
            // user.signingkey no se puede desasignar; sin gpgsign no se usa.
            doc.section("gpg", None).set("format", "openpgp").section("commit", None).set("gpgsign", "false");
        }
        doc.finish()
    }

    pub fn generate_allowed_signers(&self, state: &AppState) -> String {
        let mut sb = format!("# {HEADER}\n");
        for p in state.profiles.iter().filter(|p| p.signing == SigningMode::Ssh && !blank(&p.signing_key)) {
            let key = p.signing_key.as_deref().unwrap();
            let pub_path = self.paths.expand_tilde(key);
            let public = crate::files::file_guard::read_or_null(&pub_path).map(|s| s.trim().to_string());
            let Some(public) = public.filter(|s| !s.is_empty()) else {
                sb.push_str(&format!("# {}: {} not found\n", p.slug, key));
                continue;
            };
            // Formato: <principal> namespaces="git" <tipo> <clave> [comentario]
            let parts: Vec<&str> = public.splitn(3, ' ').filter(|s| !s.is_empty()).collect();
            if parts.len() < 2 {
                continue;
            }
            sb.push_str(&format!("{} namespaces=\"git\" {} {}\n", p.git_user_email, parts[0], parts[1]));
        }
        sb
    }

    pub fn generate_ssh_aliases(&self, state: &AppState) -> String {
        let mut sb = format!(
            "# {HEADER}\n# Aliases for tools that don't read Git's configuration. Not used in remote URLs.\n"
        );
        for p in state.profiles.iter().filter(|p| !blank(&p.ssh_key_path) && !p.host.trim().is_empty()) {
            sb.push_str(&format!(
                "\nHost {}\n    HostName {}\n    User git\n    IdentityFile {}\n    IdentitiesOnly yes\n",
                ssh_alias(p),
                ssh_host(p),
                shell_quote(p.ssh_key_path.as_deref().unwrap())
            ));
        }
        sb
    }
}
